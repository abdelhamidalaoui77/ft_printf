#include "ft_printf.h"

void	ft_putnbr(int n)
{
	char	c;

	if (n == -2147483648)
	{
		write(1, "-2147483648", 11);
		return ;
	}
	if (n < 0)
	{
		write(1,"-",1);
		n = -n;
	}
	if (n > 9)
		ft_putnbr(n / 10);
	c = n % 10 + 48;
	write(1, &c, 1);
}

int	main()
{
	ft_putnbr(-2147483648);
	write(1, "\n",1);
	ft_putnbr(2147483647);
	write(1, "\n",1);
	ft_putnbr(648);
	return (0);
}
